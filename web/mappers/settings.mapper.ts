import { urlFor } from "@/lib/image";

import type { Settings } from "@/types/settings";
import type { SettingsDTO } from "@/types/dto/settings.dto";

export function toSettingsDTO(settings: Settings): SettingsDTO {
  return {
    companyName: settings.companyName,
    tagline: settings.tagline,
    companyDescription: settings.companyDescription,
    websiteUrl: settings.websiteUrl,
    logoUrl: settings.logo ? urlFor(settings.logo as any).url() : undefined,
    email: settings.email,
    phone: settings.phone,
    whatsapp: settings.whatsapp,
    address: settings.address,
    addressNe: settings.addressNe,
    contactInfoBadge: settings.contactInfoBadge,
    contactInfoBadgeNe: settings.contactInfoBadgeNe,
    contactInfoTitle: settings.contactInfoTitle,
    contactInfoTitleNe: settings.contactInfoTitleNe,
    emailLabel: settings.emailLabel,
    emailLabelNe: settings.emailLabelNe,
    emailSubtext: settings.emailSubtext,
    emailSubtextNe: settings.emailSubtextNe,
    phoneLabel: settings.phoneLabel,
    phoneLabelNe: settings.phoneLabelNe,
    phoneSubtext: settings.phoneSubtext,
    phoneSubtextNe: settings.phoneSubtextNe,
    locationLabel: settings.locationLabel,
    locationLabelNe: settings.locationLabelNe,
    storeOpenLabel: settings.storeOpenLabel,
    storeOpenLabelNe: settings.storeOpenLabelNe,
    googleMapsUrl: settings.googleMapsUrl,
    businessHours: settings.businessHours,
    businessHoursNe: settings.businessHoursNe,
    facebook: settings.facebook,
    instagram: settings.instagram,
    tiktok: settings.tiktok,
    secondaryPhone: settings.secondaryPhone,
    footerDescription: settings.footerDescription,
    footerDescriptionNe: settings.footerDescriptionNe,
    copyright: settings.copyright,
    cookieConsentTitle: settings.cookieConsentTitle,
    cookieConsentDescription: settings.cookieConsentDescription,
    essentialCookiesLabel: settings.essentialCookiesLabel,
    acceptAllCookiesLabel: settings.acceptAllCookiesLabel,
    privacyPolicyUrl: settings.privacyPolicyUrl,
    socialLinks: settings.socialLinks,
  };
}